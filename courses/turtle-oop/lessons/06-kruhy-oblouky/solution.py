import turtle

t = turtle.Turtle()
t.penup()
t.goto(0, -100)
t.pendown()
t.circle(60)
t.penup()
t.goto(0, 20)
t.pendown()
t.circle(40)
t.penup()
t.goto(0, 100)
t.pendown()
t.circle(25)
t.penup()
t.goto(-8, 130)
t.dot(6, "black")
t.goto(8, 130)
t.dot(6, "black")
t.goto(-10, 115)
t.setheading(270)
t.pendown()
t.circle(10, 180)
turtle.done()
