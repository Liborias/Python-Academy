import turtle

turtle.bgcolor("black")
turtle.colormode(255)
t = turtle.Turtle()
t.penup()
t.goto(-100, 0)
t.pendown()
t.pencolor("red")
t.pensize(2)
t.forward(200)
t.penup()
t.goto(-100, -30)
t.pendown()
t.pencolor("#00ff00")
t.pensize(4)
t.forward(200)
t.penup()
t.goto(-100, -60)
t.pendown()
t.pencolor(255, 165, 0)
t.pensize(6)
t.forward(200)
turtle.done()
