import turtle

t = turtle.Turtle()      # vytvoříme želvu
t.forward(100)           # čára doprava
t.left(90)               # otočka doleva o 90 stupňů
t.forward(50)            # čára nahoru
t.right(45)              # otočka doprava o 45 stupňů
t.forward(70)            # šikmá čára
turtle.done()            # okno zůstane otevřené
